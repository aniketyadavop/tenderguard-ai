        # Deterministic document audit hash
        audit_hash = hashlib.sha256(f"{vendor.id}:{vendor.name}:{vendor.overall_status}:{tender_ref}".encode("utf-8")).hexdigest()
        page.insert_text((margin_x + 10, y + 28), f"SHA256: {audit_hash}", fontsize=7.5, color=(0.2, 0.2, 0.2), fontname="helv")
        page.insert_text(
            (margin_x + 10, y + 40),
            "Zero-Retention Standard: All original files were evaluated in volatile memory and purged immediately post-analysis.",
            fontsize=7,
            color=(0.35, 0.45, 0.4),
            fontname="helv"
        )

        # 7. Signature Blocks
        y_sig = y + 70
        page.draw_line(pymupdf.Point(margin_x + 20, y_sig + 35), pymupdf.Point(margin_x + 180, y_sig + 35), color=(0.5, 0.5, 0.5))
        page.insert_text((margin_x + 25, y_sig + 46), "TenderGuard AI System", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + 25, y_sig + 56), "Automated OCR & Vision-Language Engine", fontsize=6.8, color=(0.4, 0.4, 0.4), fontname="helv")

        page.draw_line(pymupdf.Point(margin_x + width - 180, y_sig + 35), pymupdf.Point(margin_x + width - 20, y_sig + 35), color=(0.5, 0.5, 0.5))
        page.insert_text((margin_x + width - 175, y_sig + 46), "Competent Procurement Officer", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + width - 175, y_sig + 56), "Tender Inviting Authority / GeM Committee", fontsize=6.8, color=(0.4, 0.4, 0.4), fontname="helv")

        pdf_bytes = doc.tobytes()
        doc.close()
        return pdf_bytes
