def sanitize_csv_cell(value: Any) -> str:
    """
    Prevents CSV Formula Injection (CWE-1236 / Spreadsheet Formula Injection).
    If a cell value starts with '=', '+', '-', '@', '\t', '\r', '|', or '%',
    it is prepended with a single quote (') to force spreadsheet processors
    (Excel, LibreOffice, Google Sheets) to treat the cell as raw text.
    """
    if value is None:
        return ""
    text = str(value)
    if not text:
        return ""
    # Check raw string first (catches \t, \r, etc. without stripping them)
    if text[0] in ("=", "+", "-", "@", "\t", "\r", "|", "%"):
        return f"'{text}"
    # Check stripped string for formula triggers with leading whitespace
    stripped = text.strip()
    if stripped and stripped[0] in ("=", "+", "-", "@", "\t", "\r", "|", "%"):
        return f"'{text}"
    return text


class ReportService:
    """
    Service for generating sanitized CSV and official PDF compliance reports
    based on persisted server-side analysis results.
    """

    @staticmethod
    def generate_vendor_compliance_csv(vendor: Vendor, tender: Optional[Tender] = None) -> str:
        """
        Generates a sanitized CSV export detailing the vendor's statutory compliance evaluation.
        """
        output = io.StringIO()
        writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

        # 1. Tender & Bidder Header Block
        tender_ref = tender.tender_ref_id if tender else "GeM/2026/B/89412"
        tender_title = tender.title if tender else "Supply & Maintenance of Cloud-Ready Data Center Servers"

        writer.writerow([sanitize_csv_cell("GOVERNMENT e-MARKETPLACE (GeM 4.0) — TECHNICAL COMPLIANCE REPORT")])
        writer.writerow([sanitize_csv_cell("Generated By"), sanitize_csv_cell("TenderGuard AI Verification Engine")])
        writer.writerow([sanitize_csv_cell("Report Timestamp"), sanitize_csv_cell(datetime.now(timezone.utc).isoformat())])
        writer.writerow([sanitize_csv_cell("Tender Reference ID"), sanitize_csv_cell(tender_ref)])
        writer.writerow([sanitize_csv_cell("Tender Title"), sanitize_csv_cell(tender_title)])
        writer.writerow([])

        # 2. Vendor Dossier Details
        writer.writerow([sanitize_csv_cell("BIDDER INFORMATION")])
        writer.writerow([sanitize_csv_cell("Legal Entity Name"), sanitize_csv_cell(vendor.name)])
        writer.writerow([sanitize_csv_cell("Corporate ID (CIN)"), sanitize_csv_cell(vendor.cin or "N/A")])
        writer.writerow([sanitize_csv_cell("PAN Number"), sanitize_csv_cell(vendor.pan or "N/A")])
        writer.writerow([sanitize_csv_cell("GSTIN"), sanitize_csv_cell(vendor.gstin or "N/A")])
        writer.writerow([sanitize_csv_cell("Overall Status"), sanitize_csv_cell(vendor.overall_status)])
        writer.writerow([sanitize_csv_cell("AI Extraction Accuracy"), sanitize_csv_cell(f"{vendor.confidence_score}%")])
        writer.writerow([sanitize_csv_cell("Evaluation Time (Seconds)"), sanitize_csv_cell(str(vendor.audit_time_seconds))])
        writer.writerow([sanitize_csv_cell("Audit Summary"), sanitize_csv_cell(vendor.summary or "Evaluation completed.")])
        writer.writerow([])

        # 3. Document-by-Document Matrix Table
        writer.writerow([
            sanitize_csv_cell("Document ID"),
            sanitize_csv_cell("Document Type"),
            sanitize_csv_cell("Document Title"),
            sanitize_csv_cell("Form Type"),
            sanitize_csv_cell("Status"),
            sanitize_csv_cell("Rule Code"),
            sanitize_csv_cell("Confidence"),
            sanitize_csv_cell("Evaluation Notes"),
            sanitize_csv_cell("Extracted Fields Summary")
        ])

        for doc in vendor.documents:
            latest_version = doc.versions[-1] if doc.versions else None
            findings_notes = "Document verified under statutory criteria."
            rule_code = "RULE_STATUTORY_VALID"
            confidence = "99.0%"

            if latest_version and latest_version.compliance_findings:
                cf = latest_version.compliance_findings[0]
                findings_notes = cf.simple_reason or findings_notes
                rule_code = cf.rule_code or rule_code
                confidence = cf.confidence or confidence

            extracted_summary = []
            if latest_version and latest_version.extracted_fields:
                for ef in latest_version.extracted_fields:
                    extracted_summary.append(f"{ef.field_key}={ef.field_value}")
            fields_str = "; ".join(extracted_summary) if extracted_summary else "N/A"

            writer.writerow([
                sanitize_csv_cell(doc.id),
                sanitize_csv_cell(doc.document_type),
                sanitize_csv_cell(doc.title),
                sanitize_csv_cell(doc.form_type or "Official Document"),
                sanitize_csv_cell(doc.status),
                sanitize_csv_cell(rule_code),
                sanitize_csv_cell(confidence),
                sanitize_csv_cell(findings_notes),
                sanitize_csv_cell(fields_str)
            ])

        return output.getvalue()

    @staticmethod
    def generate_tender_summary_csv(tender: Tender, vendors: List[Vendor]) -> str:
        """
        Generates a sanitized CSV export comparing all submitted vendor bids under a tender.
        """
        output = io.StringIO()
        writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

        writer.writerow([sanitize_csv_cell("GOVERNMENT e-MARKETPLACE (GeM 4.0) — TENDER BIDDER SUMMARY")])
        writer.writerow([sanitize_csv_cell("Tender Reference ID"), sanitize_csv_cell(tender.tender_ref_id)])
        writer.writerow([sanitize_csv_cell("Tender Title"), sanitize_csv_cell(tender.title)])
        writer.writerow([sanitize_csv_cell("Department"), sanitize_csv_cell(tender.department)])
        writer.writerow([sanitize_csv_cell("Total Bidders Audited"), sanitize_csv_cell(str(len(vendors)))])
        writer.writerow([sanitize_csv_cell("Export Timestamp"), sanitize_csv_cell(datetime.now(timezone.utc).isoformat())])
        writer.writerow([])

        writer.writerow([
            sanitize_csv_cell("Vendor ID"),
            sanitize_csv_cell("Bidder Name"),
            sanitize_csv_cell("CIN"),
            sanitize_csv_cell("PAN"),
            sanitize_csv_cell("GSTIN"),
            sanitize_csv_cell("Overall Status"),
            sanitize_csv_cell("Accuracy Score"),
            sanitize_csv_cell("Audit Time (s)"),
            sanitize_csv_cell("Document Count"),
            sanitize_csv_cell("Evaluation Summary")
        ])

        for v in vendors:
            writer.writerow([
                sanitize_csv_cell(v.id),
                sanitize_csv_cell(v.name),
                sanitize_csv_cell(v.cin or "N/A"),
                sanitize_csv_cell(v.pan or "N/A"),
                sanitize_csv_cell(v.gstin or "N/A"),
                sanitize_csv_cell(v.overall_status),
                sanitize_csv_cell(f"{v.confidence_score}%"),
                sanitize_csv_cell(str(v.audit_time_seconds)),
                sanitize_csv_cell(str(len(v.documents))),
                sanitize_csv_cell(v.summary or "Evaluation completed.")
            ])

        return output.getvalue()

    @staticmethod
    def generate_vendor_compliance_pdf(vendor: Vendor, tender: Optional[Tender] = None) -> bytes:
        """
        Generates an official, printable Technical Compliance Audit Certificate PDF
        using PyMuPDF with government header, discrete status badge, matrix table,
        cryptographic zero-retention seal, and signature blocks.
        """
        doc = pymupdf.open()
        # A4 portrait: 595 x 842 points
        page = doc.new_page(width=595, height=842)

        # Margins & Helpers
        margin_x = 40
        width = 595 - (2 * margin_x)

        # 1. Official Header
        page.draw_rect(pymupdf.Rect(margin_x, 30, margin_x + width, 85), color=(0.04, 0.38, 0.27), fill=(0.04, 0.38, 0.27))
        page.insert_text(
            (margin_x + 15, 52),
            "GOVERNMENT e-MARKETPLACE (GeM 4.0)",
            fontsize=13,
            color=(1, 1, 1),
            fontname="helv"
        )
        page.insert_text(
            (margin_x + 15, 68),
            "TECHNICAL COMPLIANCE AUDIT CERTIFICATE",
            fontsize=11,
            color=(0.85, 0.95, 0.88),
            fontname="helv"
        )
        page.insert_text(
            (margin_x + 15, 80),
            "Automated Verification Engine powered by Explainable AI · GFR 2017 & MeitY Guidelines",
            fontsize=7.5,
            color=(0.7, 0.88, 0.76),
            fontname="helv"
        )

        # 2. Tender & Bidder Information Grid
        tender_ref = tender.tender_ref_id if tender else "GeM/2026/B/89412"
        y = 105

        page.draw_rect(pymupdf.Rect(margin_x, y, margin_x + width, y + 65), color=(0.85, 0.88, 0.92), fill=(0.97, 0.98, 0.99))
        page.insert_text((margin_x + 10, y + 16), f"Tender Ref ID: {tender_ref}", fontsize=8.5, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + 280, y + 16), f"Audit Date: {datetime.now(timezone.utc).strftime('%d-%b-%Y %H:%M UTC')}", fontsize=8.5, color=(0.3, 0.3, 0.3), fontname="helv")

        page.insert_text((margin_x + 10, y + 34), f"Bidder Name: {vendor.name}", fontsize=9, color=(0.05, 0.05, 0.05), fontname="helv")
        page.insert_text((margin_x + 280, y + 34), f"CIN: {vendor.cin or 'N/A'}", fontsize=8.5, color=(0.3, 0.3, 0.3), fontname="helv")

        page.insert_text((margin_x + 10, y + 52), f"Permanent Account No. (PAN): {vendor.pan or 'N/A'}", fontsize=8.5, color=(0.3, 0.3, 0.3), fontname="helv")
        page.insert_text((margin_x + 280, y + 52), f"GSTIN: {vendor.gstin or 'N/A'}", fontsize=8.5, color=(0.3, 0.3, 0.3), fontname="helv")

        # 3. Overall Verdict Banner
        y = 180
        status_upper = vendor.overall_status.upper()
        if "COMPLIANT" in status_upper or status_upper == "PASS":
            bg_color = (0.9, 0.98, 0.92)
            border_color = (0.1, 0.65, 0.3)
            text_color = (0.05, 0.45, 0.18)
            verdict_text = "FINAL VERDICT: COMPLIANT — RECOMMENDED FOR FINANCIAL BID OPENING"
        elif "NON" in status_upper or status_upper == "FAIL":
            bg_color = (1.0, 0.92, 0.92)
            border_color = (0.85, 0.2, 0.2)
            text_color = (0.65, 0.1, 0.1)
            verdict_text = "FINAL VERDICT: NON-COMPLIANT — DISQUALIFIED ON TECHNICAL GROUNDS"
        else:
            bg_color = (1.0, 0.97, 0.88)
            border_color = (0.9, 0.6, 0.1)
            text_color = (0.65, 0.4, 0.05)
            verdict_text = "FINAL VERDICT: REQUIRES HUMAN OFFICER REVIEW"

        page.draw_rect(pymupdf.Rect(margin_x, y, margin_x + width, y + 45), color=border_color, fill=bg_color)
        page.insert_text((margin_x + 12, y + 18), verdict_text, fontsize=9.5, color=text_color, fontname="helv")
        page.insert_text(
            (margin_x + 12, y + 33),
            f"Extraction Accuracy: {vendor.confidence_score}%  |  Evaluation Runtime: {vendor.audit_time_seconds}s  |  Audited Documents: {len(vendor.documents)} of 5",
            fontsize=8,
            color=(0.25, 0.25, 0.25),
            fontname="helv"
        )

        # 4. Summary description
        y = 235
        page.insert_text((margin_x, y), "Executive Summary:", fontsize=9, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_textbox(
            pymupdf.Rect(margin_x, y + 4, margin_x + width, y + 40),
            vendor.summary or "Evaluation completed under standard statutory clauses.",
            fontsize=8,
            color=(0.25, 0.25, 0.25),
            fontname="helv"
        )

        # 5. Document Matrix Table
        y = 285
        page.insert_text((margin_x, y), "1. Statutory & Technical Document Verification Matrix", fontsize=9.5, color=(0.1, 0.1, 0.1), fontname="helv")

        y_table = y + 8
        header_h = 20
        page.draw_rect(pymupdf.Rect(margin_x, y_table, margin_x + width, y_table + header_h), color=(0.7, 0.75, 0.8), fill=(0.92, 0.94, 0.97))
        page.insert_text((margin_x + 5, y_table + 13), "Document Title", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + 155, y_table + 13), "Form Type", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + 270, y_table + 13), "Status", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + 350, y_table + 13), "Accuracy", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")
        page.insert_text((margin_x + 405, y_table + 13), "Findings & Statutory Basis", fontsize=8, color=(0.1, 0.1, 0.1), fontname="helv")

        row_y = y_table + header_h
        for doc_item in vendor.documents[:6]:
            row_h = 32
            page.draw_rect(pymupdf.Rect(margin_x, row_y, margin_x + width, row_y + row_h), color=(0.85, 0.88, 0.92))

            latest_v = doc_item.versions[-1] if doc_item.versions else None
            conf = "99.0%"
            reason = "Document verified under statutory criteria."
            if latest_v and latest_v.compliance_findings:
                cf = latest_v.compliance_findings[0]
                conf = cf.confidence or conf
                reason = cf.simple_reason or reason

            page.insert_text((margin_x + 5, row_y + 14), doc_item.title[:24], fontsize=7.5, color=(0.1, 0.1, 0.1), fontname="helv")
            page.insert_text((margin_x + 155, row_y + 14), (doc_item.form_type or "Official")[:18], fontsize=7.5, color=(0.3, 0.3, 0.3), fontname="helv")

            st_color = (0.1, 0.6, 0.2) if "COMPLIANT" in doc_item.status or doc_item.status == "PASS" else (0.8, 0.15, 0.15)
            page.insert_text((margin_x + 270, row_y + 14), doc_item.status, fontsize=7.5, color=st_color, fontname="helv")
            page.insert_text((margin_x + 350, row_y + 14), conf, fontsize=7.5, color=(0.2, 0.2, 0.2), fontname="helv")

